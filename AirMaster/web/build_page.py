"""Compresses index.html into AirHandlerPico/web_page.h, which is what the firmware serves. Run it after editing the page."""
import gzip, os
here = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(here, "index.html"), "rb").read()
gz = gzip.compress(html, 9, mtime=0)
rows = [", ".join("0x%02x" % b for b in gz[i:i + 16]) for i in range(0, len(gz), 16)]
out = os.path.join(here, "..", "..", "AirHandlerPico", "web_page.h")
with open(out, "w") as f:
    f.write("// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0\n// Copyright David Lewis\n")
    f.write("// Generated by AirMaster/web/build_page.py from index.html. Do not edit.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n")
    f.write("const uint8_t WEB_PAGE_GZ[] = {\n" + ",\n".join(rows) + "\n};\nconst size_t WEB_PAGE_GZ_LEN = sizeof(WEB_PAGE_GZ);\n")
print("page %d bytes, %d compressed" % (len(html), len(gz)))
