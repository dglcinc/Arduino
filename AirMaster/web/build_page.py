"""Compresses index.html into AirHandlerPico/web_page.h, with the home-screen icons and their web manifest, which is
what the firmware serves. Run it after editing the page or redrawing the icons."""
import gzip, os
here = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(here, "index.html"), "rb").read()
gz = gzip.compress(html, 9, mtime=0)
out = os.path.join(here, "..", "..", "AirHandlerPico", "web_page.h")
MANIFEST = ('{"name":"AirMaster","short_name":"AirMaster","start_url":"/","display":"browser","background_color":"#ffffff",'
            '"theme_color":"#135ea8","icons":[{"src":"/icon-192.png","sizes":"192x192","type":"image/png","purpose":"any maskable"},'
            '{"src":"/icon-512.png","sizes":"512x512","type":"image/png","purpose":"any maskable"}]}').encode()


def array(name, data):
    r = [", ".join("0x%02x" % b for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return "const uint8_t %s[] = {\n" % name + ",\n".join(r) + "\n};\nconst size_t %s_LEN = sizeof(%s);\n" % (name, name)


# the home-screen icons (gen_icon.py draws them) and the web manifest that names them for Android
icons = {px: open(os.path.join(here, "icon-%d.png" % px), "rb").read() for px in (180, 192, 512)}
with open(out, "w") as f:
    f.write("// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0\n// Copyright David Lewis\n")
    f.write("// Generated by AirMaster/web/build_page.py from index.html and the icon PNGs. Do not edit.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n")
    f.write(array("WEB_PAGE_GZ", gz))
    for px, data in icons.items():
        f.write(array("WEB_ICON_%d" % px, data))
    f.write(array("WEB_MANIFEST", MANIFEST))
print("page %d bytes, %d compressed; icons %s; manifest %d" % (len(html), len(gz), ", ".join(str(len(d)) for d in icons.values()), len(MANIFEST)))
